/// The four languages the platform speaks, in the order the web lists them.
/// Kinyarwanda is the default here as it is on the website: it is what a motari
/// who has never touched the switch should read.
class Lang {
  static const codes = ['en', 'fr', 'kinyy', 'sw'];
  static const fallback = 'en';
  static const initial = 'kinyy';

  static const names = {
    'en': 'English',
    'fr': 'Français',
    'kinyy': 'Kinyarwanda',
    'sw': 'Kiswahili',
  };

  /// Two letters for the switch. "kinyy" is our internal key; RW is what people read.
  static String short(String code) => code == 'kinyy' ? 'RW' : code.toUpperCase();
}

/// The language in force. Everything that draws text listens to this, so the
/// whole app turns over the moment it changes.
final appLanguage = ValueNotifier<String>(Lang.initial);

const _prefsKey = 'motari.language';

/// Read the stored choice at startup; a phone with none gets Kinyarwanda.
Future<void> restoreLanguage() async {
  final prefs = await SharedPreferences.getInstance();
  final stored = prefs.getString(_prefsKey);
  if (stored != null && Lang.codes.contains(stored)) appLanguage.value = stored;
}

Future<void> setLanguage(String code) async {
  if (!Lang.codes.contains(code) || code == appLanguage.value) return;
  appLanguage.value = code;
  final prefs = await SharedPreferences.getInstance();
  await prefs.setString(_prefsKey, code);
}

/// Short month names, in each language. These sit outside the catalogue
/// because they are reached by number rather than by key, and a list keeps the
/// twelve of them together where they can be read at a glance.
const Map<String, List<String>> _months = {
  'en': ['Jan', 'Feb', 'Mar', 'Apr', 'May', 'Jun',
         'Jul', 'Aug', 'Sep', 'Oct', 'Nov', 'Dec'],
  'fr': ['janv', 'févr', 'mars', 'avr', 'mai', 'juin',
         'juil', 'août', 'sept', 'oct', 'nov', 'déc'],
  'kinyy': ['Mut', 'Gas', 'Wer', 'Mat', 'Gic', 'Kam',
            'Nya', 'Kan', 'Nze', 'Ukw', 'Ugu', 'Uku'],
  'sw': ['Jan', 'Feb', 'Mac', 'Apr', 'Mei', 'Jun',
         'Jul', 'Ago', 'Sep', 'Okt', 'Nov', 'Des'],
};

/// "Aug", in whichever language is in force.
String monthShort(int month) {
  final names = _months[appLanguage.value] ?? _months[Lang.fallback]!;
  return names[(month - 1).clamp(0, 11)];
}

/// Translate. `{name}` placeholders are filled from [vars]; a key with no
/// translation falls back to English rather than showing the key itself.
String t(String key, [Map<String, Object?>? vars]) {
  final table = _catalogue[appLanguage.value] ?? const {};
  var text = table[key] ?? _catalogue[Lang.fallback]![key] ?? key;
  if (vars != null) {
    vars.forEach((name, value) {
      text = text.replaceAll('{$name}', '${value ?? ''}');
    });
  }
  return text;
}

/// Translate into a named language rather than the one on screen.
///
/// Only the spoken turns need this. A phone with no Kinyarwanda voice still
/// has to say something, so the navigator picks a language the phone can
/// actually pronounce and asks for the words in that one.
String tIn(String lang, String key, [Map<String, Object?>? vars]) {
  final table = _catalogue[lang] ?? const {};
  var text = table[key] ?? _catalogue[Lang.fallback]![key] ?? key;
  if (vars != null) {
    vars.forEach((name, value) {
      text = text.replaceAll('{$name}', '${value ?? ''}');
    });
  }
  return text;
}

